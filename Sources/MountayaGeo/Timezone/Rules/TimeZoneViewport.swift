/// timeZoneViewport is the viewport a map opens on for a reader in a time zone, an IANA name such
/// as `Europe/Zurich`, or nil where the table answers none.
///
/// The zone is an argument, never a read of the ambient zone, and it is a name, never a platform
/// time zone: a probe of the environment is not a geographic fact, and the table answers the same
/// on every host, whatever tz database the host carries. A zone is read under the name a runtime
/// reports for it as well as under its own: an older spelling the tz database keeps as a link
/// (`Asia/Calcutta` for `Asia/Kolkata`), and a zone it merged into a neighbour, which answers the
/// zone that holds it today (`America/Montreal` answers `America/Toronto`). A name is matched
/// exactly, letter case and white space included.
///
/// The table is the one `geo/timezone-viewport.json` publishes in its constants, every zone of a
/// country and every name a runtime reports in another form, and answers no viewport for any other
/// name: a link no runtime reports (`US/Pacific`), a zone of no country (`Etc/UTC`, an Antarctic
/// station) and a name that is no zone answer nil, and Macquarie Island, filed under Antarctica,
/// answers Australia's.
public func timeZoneViewport(_ timeZone: String) -> MapViewport? {
  zoneViewports[reportedZoneNames[timeZone] ?? timeZone]
}


    /// and the value a rating on it must carry back as
    /// AgentRunFeedbackParams.message_index.
    ///
    /// It travels on the event because a client cannot derive it: a client that
    /// reconnects mid-run counts only the replies it has seen, while the run
    /// counts every one, so a number kept by the client would name the wrong
    /// message.
    ///
